"""Render exactly what the owner's inbox would receive — no AWS needed.

Writes email_preview.html (the real subject/text/html from the app) and
opens it in the default browser.

Usage:  .venv\\Scripts\\python scripts\\preview_email.py
"""

import html
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.models import Inquiry  # noqa: E402
from app.services.email_service import _html_body, _subject, _text_body  # noqa: E402

OWNER = "menefides@gmail.com"


def main() -> int:
    inquiry = Inquiry(
        id=1,
        name="Jane Doe",
        email="jane@example.com",
        phone="+91 98765 43210",
        project_type="Apartment",
        project_location="Bengaluru",
        created_at=datetime.now(timezone.utc),
    )

    subject = _subject(inquiry)
    text = _text_body(inquiry)
    html_body = _html_body(inquiry)

    page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>AURELIA — email preview</title>
<style>
  body {{ background:#12141a; color:#cfc9bd; font-family:Georgia,serif; margin:0; padding:40px; }}
  .card {{ max-width:720px; margin:auto; }}
  h1 {{ font-weight:normal; color:#c8b98f; font-size:22px; }}
  .label {{ text-transform:uppercase; letter-spacing:3px; font-size:11px; color:#8a8f98; margin-top:36px; }}
  pre {{ white-space:pre-wrap; background:#1b1e26; padding:20px; border:1px solid #2a2e38; font-size:13px; }}
  .frame {{ border:1px solid #2a2e38; }}
  .meta {{ font-size:12px; color:#8a8f98; }}
</style>
</head>
<body>
<div class="card">
  <p class="meta">Simulated delivery to <strong>{html.escape(OWNER)}</strong> (From: {html.escape(OWNER)}, Reply-To: {html.escape(inquiry.email)})</p>
  <div class="label">Subject</div>
  <h1>{html.escape(subject)}</h1>
  <div class="label">HTML body — this is the actual mail content sent by the app</div>
  <div class="frame">{html_body}</div>
  <div class="label">Plain-text body (sent alongside)</div>
  <pre>{html.escape(text)}</pre>
  <p class="meta">Generated by scripts/preview_email.py — the exact output of _subject/_text_body/_html_body.</p>
</div>
</body>
</html>
"""
    out = Path(__file__).resolve().parents[1] / "email_preview.html"
    out.write_text(page, encoding="utf-8")

    print(f"Subject: {subject}")
    print(f"Written: {out}")
    try:
        os.startfile(out)  # opens the default browser on Windows
    except OSError:
        print("Open that file in your browser to review the mail.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
